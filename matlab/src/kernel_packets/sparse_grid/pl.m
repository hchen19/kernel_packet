function x = pl(j, lo, hi)
% Plumlee's design of level j <= 16, nested in j
X = [.5, .5; .125, .875; .25, .75; 0, 1; .375, .625; .25-1/16, .75+1/16; 1-1/16, 1/16; .5-1/16, .5+1/16;
    .3125, .6875; .25+1/32, .75-1/32; 1/32, 1-1/32; .875+1/32, .125-1/32; .875-1/32, .125+1/32;
    .375+1/32, .625-1/32; .5-1/32, .5+1/32; .25-1/32, .75+1/32];
x = lo + unique(X(1:j,:))' * (hi - lo);
end
